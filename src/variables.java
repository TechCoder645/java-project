public class variables {
    public static void main(String[] args) {
        // Create //declare
        int age;
        // System.out.println(age);
        // assign value
        age=10;
        age=11;
        System.out.println(age);

        //define or intialize
        int totalMarks=20;
        System.out.println(totalMarks);

        //case sensitive
         int weight=80;
         int WEIGHT=90;
        System.out.println(
                "weight:"+ weight
        );
        System.out.println(
                "WEIGHT:"+ WEIGHT
        );

        //Starting letter
        int marks=10;
        int MARKS=11;
        int _marks=12;
        int $marks=13;

        //subsequent letters
        int height5=20;
        int height_love=30;
        int height$love=45;
        int height_=23;
        int height$=12;

        //no reserved keyword
        //int class=22;(if we take it occurs error)

        //constants
        int DAY_IN_YEAR=365; //WE should use variable name in capital for convinent




    }
}
